mkdirSync(fileURLToPath(new URL('../resume/', import.meta.url)), { recursive: true });
writeFileSync(htmlPath, html, 'utf8');
console.log(`Wrote ${htmlPath}`);

const browserCandidates = [
  process.env.CHROME_PATH,
  'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
  'C:/Program Files/Microsoft/Edge/Application/msedge.exe',
  'C:/Program Files/Google/Chrome/Application/chrome.exe',
  'C:/Program Files (x86)/Google/Chrome/Application/chrome.exe',
  '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  '/usr/bin/google-chrome',
  '/usr/bin/chromium',
  '/usr/bin/chromium-browser',
].filter(Boolean);
const browser = browserCandidates.find((p) => existsSync(p));

if (!browser) {
  console.log('No Edge/Chrome found. Open the HTML above in a browser and print to A4 PDF, then save it as:');
  console.log(`  ${pdfPath}`);
  process.exit(0);
}

// A throwaway profile is required for headless printing, and keeps it independent of any open browser.
const profileDir = mkdtempSync(join(tmpdir(), 'resume-print-'));
// Print to a temp file first, then copy into place: Chromium replaces files by rename, which fails
// silently if another process (indexer, antivirus, preview pane) has the old PDF open on Windows,
// and this way a failed print can never leave a half-written resume behind.
const tempPdf = join(profileDir, 'resume.pdf');
try {
  execFileSync(
    browser,
    [
      '--headless=new',
      '--disable-gpu',
      '--no-pdf-header-footer',
      '--virtual-time-budget=10000',
      `--user-data-dir=${profileDir}`,
      `--print-to-pdf=${tempPdf}`,
      new URL(`file:///${htmlPath.replace(/\\/g, '/')}`).href,
    ],
    // 'pipe' (not 'ignore') makes Node wait for the whole browser process tree, not just the launcher.
    { stdio: 'pipe', timeout: 90_000 }
  );
} catch (err) {
  console.error(`Browser exited with an error: ${err.message}`);
}

// Poll briefly in case the file lands just after the browser process exits.
for (let waited = 0; !existsSync(tempPdf) && waited < 10_000; waited += 250) {
  await new Promise((resolve) => setTimeout(resolve, 250));
}

let ok = false;
try {
  if (existsSync(tempPdf) && statSync(tempPdf).size > 10_000) {
    copyFileSync(tempPdf, pdfPath);
    ok = true;
  }
} catch (err) {
  console.error(`Could not write ${pdfPath}: ${err.message} (is the file open in another program?)`);
} finally {
  rmSync(profileDir, { recursive: true, force: true });
}

if (ok) {
  console.log(`Wrote ${pdfPath} (${Math.round(statSync(pdfPath).size / 1024)} KB)`);
} else {
  console.error('The PDF was not updated. Open the HTML above and print it to PDF manually.');
  process.exit(1);
}
